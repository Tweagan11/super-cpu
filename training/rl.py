class ActorCritic(nn.Module):
    """A BC network plus a linear value head on its trunk. Always in eval mode
    (no dropout): the logprobs stored when acting must match the update's."""

    def __init__(self, net: BCNet) -> None:
        super().__init__()
        self.net = net
        self.value = nn.Linear(net.mcfg.hidden, 1)
        nn.init.zeros_(self.value.weight)
        nn.init.zeros_(self.value.bias)
        self.eval()

    def forward(self, cont, cat, detach_value: bool = False):
        h = self.net.hidden(cont, cat)
        logits = {k: head(h) for k, head in self.net.heads.items()}
        v = self.value(h.detach() if detach_value else h).squeeze(-1)
        return logits, v

    def train(self, mode: bool = True):  # keep dropout off, whatever calls this
        return super().train(False)

    def load_weights(self, net_state: dict, value_state: dict | None) -> None:
        self.net.load_state_dict(net_state)
        if value_state is not None:
            self.value.load_state_dict(value_state)


def _clone_state(sd: dict) -> dict:
    return {k: v.detach().to("cpu", copy=True) for k, v in sd.items()}


