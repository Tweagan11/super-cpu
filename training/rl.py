def _from_env(cls, prefix: str, **overrides):
    """Build dataclass `cls`, each field from env var `prefix + NAME` if set."""
    hints = typing.get_type_hints(cls)
    kw = {}
    for f in dataclasses.fields(cls):
        raw = os.environ.get(prefix + f.name.upper())
        if raw is None or raw == "":
            continue
        t = hints[f.name]
        if t is bool:
            kw[f.name] = raw.strip().lower() in ("1", "true", "yes", "on")
        elif t in (int, float):
            kw[f.name] = t(raw)
        else:
            kw[f.name] = raw
    kw.update({k: v for k, v in overrides.items() if v is not None})
    return cls(**kw)


@dataclass(frozen=True)
class RewardConfig:
    """Per-frame reward weights. Env: SCPU_RL_REWARD_<FIELD>."""

    damage_dealt: float = 0.01         # per percent of damage the opponent took
    damage_taken: float = 0.01         # per percent the bot took (subtracted)
    stock_taken: float = 5.0           # per opponent stock lost
    stock_lost: float = 5.0            # per bot stock lost (subtracted)
    self_destruct: float = 2.0         # extra, subtracted, when a stock is lost without recent damage taken
    self_destruct_window: int = 120    # frames of no damage taken before the stock loss that make it a self-destruct
    offstage_penalty: float = 0.002    # per frame offstage beyond the grace period (subtracted)
    offstage_grace: int = 90           # frames offstage that are free (recovering is fine)
    offstage_below: float = 10.0       # also offstage when this far below the ground (stage units)
    effect_lag: int = 0                # extra frames between "applied" and "visible in state" (credit shift)


class RewardTracker:
    """Reward for a stream of frames. Feed every frame in order with `step`."""

    def __init__(self, cfg: RewardConfig = RewardConfig()) -> None:
        self.cfg = cfg
        self.reset()

    def reset(self) -> None:
        self.armed = False
        self.prev: Frame | None = None
        self.since_damage = 10 ** 9   # frames since the bot last took damage
        self.offstage_run = 0
        self.totals = dict(damage_dealt=0.0, damage_taken=0.0, stocks_taken=0, stocks_lost=0,
                           self_destructs=0, offstage_frames=0)

    def offstage(self, f: Frame) -> bool:
        _, cx, gy, lx = _layout_of(f.stage_id)
        b = f.bot
        return abs(b.pos_x - cx) > lx or b.pos_y < gy - self.cfg.offstage_below

    def step(self, f: Frame) -> float:
        c, t = self.cfg, self.totals
        if not self.armed:
            # Hardware reads 0 stocks for the first frames: wait for real ones.
            if f.bot.stocks > 0 and f.opponent.stocks > 0:
                self.armed = True
                self.prev = f
            return 0.0
        p = self.prev
        self.prev = f
        r = 0.0
        dealt = max(0.0, f.opponent.damage - p.opponent.damage)
        taken = max(0.0, f.bot.damage - p.bot.damage)
        r += c.damage_dealt * dealt - c.damage_taken * taken
        t["damage_dealt"] += dealt
        t["damage_taken"] += taken
        self.since_damage = 0 if taken > 0 else self.since_damage + 1
        if p.opponent.stocks > 0 and 0 <= f.opponent.stocks < p.opponent.stocks:
            n = p.opponent.stocks - f.opponent.stocks
            r += c.stock_taken * n
            t["stocks_taken"] += n
        if p.bot.stocks > 0 and 0 <= f.bot.stocks < p.bot.stocks:
            n = p.bot.stocks - f.bot.stocks
            r -= c.stock_lost * n
            t["stocks_lost"] += n
            if self.since_damage > c.self_destruct_window:
                r -= c.self_destruct
                t["self_destructs"] += 1
        if self.offstage(f):
            self.offstage_run += 1
            if self.offstage_run > c.offstage_grace:
                r -= c.offstage_penalty
                t["offstage_frames"] += 1
        else:
            self.offstage_run = 0
        return r


def delayed_rewards(decision_frames: Sequence[int], reward_frames: Sequence[int], rewards: Sequence[float],
                    delay: int, lag: int = 0) -> np.ndarray:
    """Reward credited to each decision.

    Decision i was made on state frame decision_frames[i]; it is applied on
    frame +delay and shows in the state of frame +delay+lag. Its reward is
    what accrued from the previous decision's target frame (exclusive) up to
    its own (inclusive): rewards[j] is the reward observed on reward_frames[j]
    (increasing). Targets past the last reward frame clamp to the end, so
    nothing is lost and the final decisions get 0.
    """
    df = np.asarray(decision_frames, np.int64)
    rf = np.asarray(reward_frames, np.int64)
    cum = np.concatenate([[0.0], np.cumsum(np.asarray(rewards, np.float64))])  # cum[k] = sum of first k rewards

    def at(frames: np.ndarray) -> np.ndarray:  # total reward observed on frames <= each
        return cum[np.searchsorted(rf, frames, side="right")]

    target = df + delay + lag
    hi = at(target)
    lo = np.concatenate([[at(target[:1] - 1)[0]], hi[:-1]]) if len(df) else hi
    return (hi - lo).astype(np.float32)


def gae(rewards: np.ndarray, values: np.ndarray, gamma: float, lam: float, last_value: float = 0.0) -> tuple[np.ndarray, np.ndarray]:
    """(advantages, returns) for one episode. `last_value` is the bootstrap
    after the final step (0 for a match that ended)."""
    n = len(rewards)
    adv = np.zeros(n, np.float32)
    running = 0.0
    for t in range(n - 1, -1, -1):
        nxt = values[t + 1] if t + 1 < n else last_value
        delta = rewards[t] + gamma * nxt - values[t]
        running = delta + gamma * lam * running
        adv[t] = running
    return adv, adv + values.astype(np.float32)


@dataclass(frozen=True)
class RLConfig:
    """Everything tunable. Env: SCPU_RL_<FIELD>."""

    # acting
    delay: int = -1                    # -1: the bridge's --delay (set through configure)
    temperature: float = 1.0           # softmax temperature when sampling (and in the update)
    greedy: bool = False               # argmax instead of sampling (evaluate a checkpoint; implies learn=0)
    seed: int = 0
    # learning
    learn: bool = True
    async_learn: bool = True           # update in a background thread
    learn_device: str = "cpu"          # cpu or cuda (acting is always cpu)
    matches_per_update: int = 2
    min_decisions: int = 120           # matches with fewer decisions are thrown away
    lr: float = 1e-4
    gamma: float = 0.99                # per frame: horizon ~ 1.7 s
    lam: float = 0.95
    clip: float = 0.2
    epochs: int = 4
    minibatch: int = 2048
    vf_coef: float = 0.5
    ent_coef: float = 0.01
    kl_coef: float = 0.05              # weight of KL(pi || pi_BC)
    target_kl: float = 0.03            # stop an update's epochs early past 1.5x this
    max_grad_norm: float = 0.5
    value_warmup_updates: int = 2      # updates that only train the value head
    # bookkeeping
    run: str = ""                      # run name (default: timestamp, or the resumed run's)
    resume: str = ""                   # RL checkpoint (file or run dir)
    out_dir: str = ""                  # data/rl/<run> by default
    ckpt_dir: str = ""                 # checkpoints/rl/<run> by default
    ckpt_every: int = 5                # matches
    win_window: int = 20               # matches in the rolling win rate
    best_min_matches: int = 10


