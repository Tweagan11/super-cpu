"""RL fine-tuning of the behavior-cloned policy (SSB-21): PPO against the level 9 CPU.

    SCPU_CHECKPOINT=checkpoints/<run>/best.pt python -m bridge.run --policy rl \\
        --auto-rematch --stocks 1 --log

Real time is the bottleneck (~60 frames/s, maybe 30 matches/hour), so this
starts from the BC weights and keeps everything cheap and conservative.

## Acting and learning are split

- `RLPolicy` (registered as `--policy rl`) acts every frame with the *current
  acting weights*: BC features -> one forward pass -> sample each head from its
  softmax. Per decision it records (features, action classes, logprob, value)
  and the reward the frame produced. act() costs the BC forward (~0.12 ms)
  plus a few numpy ops; no autograd, one CPU thread.
- When a match ends (the bridge tells the policy through `on_match_end`) the
  match becomes an `Episode` and goes to the `Learner`. The learner runs in a
  background thread (own copy of the model, on `learn_device`, cpu or cuda),
  so the frame loop and the menu presses are never blocked. Every
  `matches_per_update` matches it runs a PPO update, then publishes the new
  weights. The policy swaps them in at the *start of the next match* (never in
  the middle of one), so every episode is generated by exactly one set of
  weights. If an update isn't done yet, the next match just plays with the
  old weights and picks the new ones up the match after.
  `async_learn=0` runs updates inline instead (tests, debugging).

## Reward (RewardConfig), from bridge Frame fields only

Per frame, bot perspective: damage_dealt * (opponent damage increase) -
damage_taken * (bot damage increase) + stock_taken per opponent stock lost -
stock_lost per bot stock lost. Extras: self_destruct (extra penalty on a stock
loss when the bot took no damage in the previous `self_destruct_window`
frames, i.e. it probably fell off by itself) and offstage_penalty per frame
spent offstage beyond `offstage_grace` frames (past the stage's ledge
horizontally, or below the ground). Damage resets to 0 on a stock loss, so only
increases count. Stocks read 0 for the first few frames of a match on
hardware: rewards stay 0 and nothing is tracked until both fighters show
stocks > 0, and a stock only counts as lost when it goes down from a value > 0.

## Delay and credit assignment

The decision made on state frame t is applied on frame t + delay (the bridge
passes its --delay to the policy through `configure`), and its effect shows up
in the state of frame t + delay + `effect_lag` (default 0, see
`delayed_rewards`). So the reward credited to decision t is what happened on
that later frame, like train_bc labels a state with the input of frame t + d.
Frames the stream skipped are handled by frame number (the reward of a skipped
gap lands on the next frame seen). The rewards of the last `delay` frames of a
match are credited to the last decisions. GAE then runs over decisions as
usual with the match end as terminal (value 0 after it).

## Not forgetting BC

- KL(pi || pi_BC) penalty per head, weight `kl_coef`, against a frozen copy of the
  BC network (the reference is stored in RL checkpoints too).
- The value head is trained alone (on the detached trunk) for the first
  `value_warmup_updates` updates, so a random critic doesn't wreck the policy.
- PPO clipping, `target_kl` early stop, entropy bonus `ent_coef`.

## Checkpoints and logs

- `checkpoints/rl/<run>/last.pt` every `ckpt_every` matches, `best.pt` whenever
  the rolling win rate (last `win_window` matches, at least `best_min_matches`
  played) beats the best so far; best.pt holds the weights that were acting.
  Both are valid BC-format checkpoints (`--policy bc` plays them greedily) with
  extra keys for resuming (`SCPU_RL_RESUME=path/to/last.pt`, or the run dir).
- `data/rl/<run>/matches.csv` (return, result, damage, stocks, entropy, ...),
  `updates.csv` (PPO stats) and `config.json`.

Config is env vars: `SCPU_CHECKPOINT` (BC checkpoint), and `SCPU_RL_<FIELD>`
for every RLConfig field, `SCPU_RL_REWARD_<FIELD>` for RewardConfig. See
training/README.md.
"""
