# Episodes and the PPO update

@dataclass
class Episode:
    cont: np.ndarray      # (N, n_cont) float32
    cat: np.ndarray       # (N, n_cat) int64
    act: np.ndarray       # (N, 3) int64 action classes
    logp: np.ndarray      # (N,) float32, at acting time
    value: np.ndarray     # (N,) float32, at acting time
    reward: np.ndarray    # (N,) float32, already credited by delay
    version: int = 0      # weights version that played it

    def __len__(self) -> int:
        return len(self.act)


def _head_logp_ent_kl(logits: dict, ref: dict | None, act: torch.Tensor, temp: float):
    """Joint logprob of `act`, mean-able entropy and KL to ref per sample."""
    logp = ent = kl = 0.0
    for i, h in enumerate(HEADS):
        lp = F.log_softmax(logits[h] / temp, dim=-1)
        logp = logp + lp.gather(1, act[:, i:i + 1]).squeeze(1)
        p = lp.exp()
        ent = ent - (p * lp).sum(-1)
        if ref is not None:
            kl = kl + (p * (lp - F.log_softmax(ref[h] / temp, dim=-1))).sum(-1)
    return logp, ent, kl


class Learner:
    """Owns the training copy of the model, the BC reference and the optimizer.
    Everything goes through `submit_*`; with async_learn it all runs on one
    worker thread, in order, so a checkpoint always follows the updates before it."""

    def __init__(self, model: ActorCritic, ref: BCNet, cfg: RLConfig, ckpt_extra: Callable[[], dict],
                 ckpt_dir: Path, updates_csv: Path | None, log: Callable[[str], None] = print,
                 opt_state: dict | None = None, updates_done: int = 0) -> None:
        self.cfg, self.log = cfg, log
        self.device = cfg.learn_device
        if self.device == "cuda" and not torch.cuda.is_available():
            raise SystemExit("SCPU_RL_LEARN_DEVICE=cuda but torch.cuda.is_available() is False")
        self.model = ActorCritic(BCNet(model.net.fcfg, model.net.mcfg)).to(self.device)
        self.model.load_state_dict(model.state_dict())
        self.ref = ref.to(self.device).eval()
        for p in self.ref.parameters():
            p.requires_grad_(False)
        self.opt = torch.optim.Adam(self.model.parameters(), lr=cfg.lr)
        if opt_state is not None:
            self.opt.load_state_dict(opt_state)
        self.rng = np.random.default_rng(cfg.seed + 17)
        self.ckpt_extra = ckpt_extra
        self.ckpt_dir = ckpt_dir
        self.updates_csv = updates_csv
        self.updates = updates_done
        self.version = updates_done
        self.last_stats: dict = {}
        self.error: BaseException | None = None
        self._buf: list[Episode] = []
        self._lock = threading.Lock()
        self._latest: tuple[int, dict, dict] | None = None
        self._q: queue.Queue = queue.Queue()
        self._thread: threading.Thread | None = None
        self._cv = threading.Condition()
        self._pending = 0

    # -- plumbing -----------------------------------------------------------
    def submit(self, kind: str, payload) -> None:
        if not self.cfg.async_learn:
            self._run(kind, payload)
            return
        with self._cv:
            self._pending += 1
        if self._thread is None:
            self._thread = threading.Thread(target=self._worker, name="rl-learner", daemon=True)
            self._thread.start()
        self._q.put((kind, payload))

    def _worker(self) -> None:
        while True:
            kind, payload = self._q.get()
            try:
                self._run(kind, payload)
            finally:
                with self._cv:
                    self._pending -= 1
                    self._cv.notify_all()

    def _run(self, kind: str, payload) -> None:
        try:
            if kind == "episode":
                self._buf.append(payload)
                if len(self._buf) >= self.cfg.matches_per_update:
                    eps, self._buf = self._buf, []
                    self._publish(self.update(eps))
            elif kind == "ckpt":
                self.save(**payload)
        except BaseException as e:  # keep playing with the old weights
            self.error = e
            self.log(f"[rl] learner error: {type(e).__name__}: {e}")

    def wait_idle(self, timeout: float | None = None) -> bool:
        end = None if timeout is None else time.monotonic() + timeout
        with self._cv:
            while self._pending:
                left = None if end is None else end - time.monotonic()
                if left is not None and left <= 0:
                    return False
                self._cv.wait(left)
        return True

    def latest_since(self, version: int) -> tuple[int, dict, dict] | None:
        with self._lock:
            return self._latest if self._latest is not None and self._latest[0] > version else None

    def _publish(self, stats: dict) -> None:
        with self._lock:
            self._latest = (self.version, _clone_state(self.model.net.state_dict()), _clone_state(self.model.value.state_dict()))
        self.last_stats = stats
        if self.updates_csv is not None:
            new = not self.updates_csv.exists()
            self.updates_csv.parent.mkdir(parents=True, exist_ok=True)
            with open(self.updates_csv, "a", newline="") as fh:
                w = csv.DictWriter(fh, fieldnames=list(stats))
                if new:
                    w.writeheader()
                w.writerow(stats)
        self.log("[rl] update {update}: {samples} samples, kl_ref {kl_ref:.4f} approx_kl {approx_kl:.4f} "
                 "entropy {entropy:.3f} vloss {value_loss:.3f} ({seconds:.1f}s{warm})".format(
                     warm=", value-only" if stats["value_only"] else "", **stats))

    # -- the update ---------------------------------------------------------
    def update(self, episodes: Sequence[Episode]) -> dict:
        cfg, dev = self.cfg, self.device
        t0 = time.monotonic()
        advs, rets = [], []
        for ep in episodes:
            a, r = gae(ep.reward, ep.value, decision_gamma(cfg), cfg.lam)
            advs.append(a)
            rets.append(r)
        cont = torch.from_numpy(np.concatenate([e.cont for e in episodes])).to(dev)
        cat = torch.from_numpy(np.concatenate([e.cat for e in episodes])).to(dev)
        act = torch.from_numpy(np.concatenate([e.act for e in episodes])).to(dev)
        old_logp = torch.from_numpy(np.concatenate([e.logp for e in episodes])).to(dev)
        adv_np = np.concatenate(advs)
        ret = torch.from_numpy(np.concatenate(rets)).to(dev)
        old_v = torch.from_numpy(np.concatenate([e.value for e in episodes])).to(dev)
        adv = torch.from_numpy((adv_np - adv_np.mean()) / (adv_np.std() + 1e-8)).to(dev)
        n = len(act)
        value_only = self.updates < cfg.value_warmup_updates
        agg = dict(policy_loss=0.0, value_loss=0.0, entropy=0.0, kl_ref=0.0, approx_kl=0.0, clipfrac=0.0, grad_norm=0.0)
        steps = 0
        stop = False
        for _ in range(cfg.epochs):
            order = self.rng.permutation(n)
            for s in range(0, n, cfg.minibatch):
                idx = torch.from_numpy(order[s:s + cfg.minibatch]).to(dev)
                logits, v = self.model(cont[idx], cat[idx], detach_value=value_only)
                vloss = F.smooth_l1_loss(v, ret[idx])
                if value_only:
                    loss = cfg.vf_coef * vloss
                    with torch.no_grad():
                        _, ent, _ = _head_logp_ent_kl(logits, None, act[idx], cfg.temperature)
                    pl = kl = approx = clipf = torch.zeros(())
                    ent_m = ent.mean()
                else:
                    with torch.no_grad():
                        ref = self.ref(cont[idx], cat[idx])
                    logp, ent, kl_s = _head_logp_ent_kl(logits, ref, act[idx], cfg.temperature)
                    log_ratio = logp - old_logp[idx]
                    ratio = log_ratio.exp()
                    a = adv[idx]
                    pl = -torch.min(ratio * a, ratio.clamp(1 - cfg.clip, 1 + cfg.clip) * a).mean()
                    ent_m, kl = ent.mean(), kl_s.mean()
                    loss = pl + cfg.vf_coef * vloss - cfg.ent_coef * ent_m + cfg.kl_coef * kl
                    with torch.no_grad():
                        approx = ((ratio - 1) - log_ratio).mean()
                        clipf = ((ratio - 1).abs() > cfg.clip).float().mean()
                self.opt.zero_grad(set_to_none=True)
                loss.backward()
                gn = nn.utils.clip_grad_norm_(self.model.parameters(), cfg.max_grad_norm)
                self.opt.step()
                steps += 1
                for k, x in (("policy_loss", pl), ("value_loss", vloss), ("entropy", ent_m), ("kl_ref", kl),
                             ("approx_kl", approx), ("clipfrac", clipf), ("grad_norm", gn)):
                    agg[k] += float(x.detach())
                if not value_only and float(approx) > 1.5 * cfg.target_kl:
                    stop = True
                    break
            if stop:
                break
        stats = {k: v / max(1, steps) for k, v in agg.items()}
        ev = 1.0 - float(((ret - old_v) ** 2).mean() / (ret.var() + 1e-8))  # explained variance of the acting-time critic
        self.updates += 1
        self.version = self.updates
        return {"update": self.updates, "time": time.strftime("%Y-%m-%d %H:%M:%S"), "matches": len(episodes),
                "samples": n, "value_only": int(value_only), "minibatch_steps": steps, "epochs_run": cfg.epochs if not stop else -1,
                **stats, "explained_var": ev, "adv_mean": float(adv_np.mean()), "return_mean": float(ret.mean()),
                "seconds": time.monotonic() - t0}

    # -- checkpoints --------------------------------------------------------
    def save(self, which: str, act_state: dict | None = None) -> None:
        """which: 'last' (learner weights) or 'best' (act_state: the weights that played)."""
        net = self.model.net
        state = act_state["net"] if act_state else _clone_state(net.state_dict())
        value = act_state["value"] if act_state else _clone_state(self.model.value.state_dict())
        extra = {
            **self.ckpt_extra(),
            "value_state": value, "ref_state": _clone_state(self.ref.state_dict()),
            "optimizer": self.opt.state_dict(), "updates": self.updates,
            "rl_config": asdict(self.cfg),
        }
        path = self.ckpt_dir / f"{which}.pt"
        tmp = path.with_suffix(".tmp")
        save_checkpoint(tmp, net, extra, state=state)
        os.replace(tmp, path)


